def sigmoid(z):
    z = np.asarray(z, dtype=float)

    result = np.empty_like(z, dtype=float)

    positive = z >= 0
    negative = ~positive

    result[positive] = 1.0 / (1.0 + np.exp(-z[positive]))

    exp_z = np.exp(z[negative])
    result[negative] = exp_z / (1.0 + exp_z)

    if result.ndim == 0:
        return float(result)

    return result


