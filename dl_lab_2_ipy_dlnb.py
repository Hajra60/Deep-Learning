def initialize_2layer(n_x, n_h, n_y):

    np.random.seed(2)

    W1 = np.random.randn(n_h, n_x) * 0.01
    b1 = np.zeros((n_h, 1))

    W2 = np.random.randn(n_y, n_h) * 0.01
    b2 = np.zeros((n_y, 1))

    parameters = {
        "W1": W1,
        "b1": b1,
        "W2": W2,
        "b2": b2
    }

    print("W1 shape:", W1.shape)
    print("b1 shape:", b1.shape)
    print("W2 shape:", W2.shape)
    print("b2 shape:", b2.shape)

    return parameters


