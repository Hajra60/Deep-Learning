def backward(X, A, Y):
    m = X.shape[1]

    dZ = A - Y

    dw = (1 / m) * np.dot(X, dZ.T)

    db = (1 / m) * np.sum(dZ)

    assert dZ.shape == (1, m)
    assert dw.shape == (X.shape[0], 1)
    assert np.isscalar(float(db))

    return dw, float(db)


