def forward(w, b, X):
    Z = np.dot(w.T, X) + b
    A = sigmoid(Z)

    assert Z.shape == (1, X.shape[1])
    assert A.shape == (1, X.shape[1])

    return A


def compute_cost(A, Y):
    m = Y.shape[1]

    cost = -(1 / m) * np.sum(
        Y * np.log(A + 1e-8)
        +
        (1 - Y) * np.log(1 - A + 1e-8)
    )

    cost = float(np.squeeze(cost))

    assert np.isscalar(cost)

    return cost

